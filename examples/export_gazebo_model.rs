//! Export nominal constants and optical fixtures as a dependency-free C++ header.
mod data {
    include!("../src/nominal_data.rs");
}
use mid360_sim::hardware::{
    NOMINAL_CYCLE_GROUPS, NOMINAL_CYCLE_S, NOMINAL_SPIN_HZ, NOMINAL_SWEEP_TURNS_PER_CYCLE,
    NominalPattern,
};
fn main() {
    let braces = |s: String| s.replace('[', "{").replace(']', "}");
    println!(
        "// SPDX-License-Identifier: MIT OR Apache-2.0\n// Derived optical parameters; original measurements retain their ownership.\n// Generated by cargo run --example export_gazebo_model.\n#pragma once\n#include <cstdint>\nnamespace mid360::data {{\ninline constexpr std::uint64_t CycleSeconds={NOMINAL_CYCLE_S}, CycleGroups={NOMINAL_CYCLE_GROUPS}, SpinHz={}, SweepTurns={NOMINAL_SWEEP_TURNS_PER_CYCLE};",
        NOMINAL_SPIN_HZ as u64
    );
    let t: Vec<_> = data::NOMINAL_TERMS.iter().map(|&(a, b)| [a, b]).collect();
    println!(
        "inline constexpr int Terms[{}][2]={};",
        t.len(),
        braces(format!("{t:?}"))
    );
    println!(
        "inline constexpr std::int16_t Coefficients[4][{}][2]={};",
        data::QUARTER_DEGREE_COEFFICIENTS[0].len(),
        braces(format!("{:?}", data::QUARTER_DEGREE_COEFFICIENTS))
    );
    println!(
        "struct Fixture {{std::uint64_t index; double direction[3];}};\ninline constexpr Fixture Fixtures[]={{"
    );
    for i in [
        0,
        1,
        2,
        3,
        200_000,
        2_400_003,
        NOMINAL_CYCLE_GROUPS * 4 - 1,
        NOMINAL_CYCLE_GROUPS * 4,
        1_000_000_000_000,
    ] {
        println!(
            "{{{i}, {}}},",
            braces(format!("{:?}", NominalPattern.direction(i)))
        );
    }
    println!("}};\n}} // namespace mid360::data");
}
