"""Fit a two-clock angular model to the pinned Livox table (requires NumPy).

Usage: python fit-mid360-pattern.py CSV --rust-output PATH --report PATH
No network access. Input checksum is mandatory; timestamps are inferred from
nominal point rate, not the misleading Time/s column. Coefficients are fitted
on the first two seconds only; all remaining samples are held out.
"""

import argparse
import hashlib
import json
from pathlib import Path

SOURCE_SHA256 = "aa1fc08b6a4400608dbd6ee832b7ea3a9c3c37197e734f60f58fe5abf762269a"
SOURCE_REVISION = "1cce1073633a062b92e30243a4c2920e45551bb5"


def main():
    import numpy as np

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path)
    parser.add_argument("--rust-output", required=True, type=Path)
    parser.add_argument("--report", required=True, type=Path)
    args = parser.parse_args()
    if hashlib.sha256(args.csv.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error("unexpected input checksum")
    rows = np.loadtxt(args.csv, delimiter=",", skiprows=1)
    if rows.shape != (800000, 3) or not np.array_equal(
        rows[:, 0], np.arange(1, 800001)
    ):
        parser.error("unexpected table shape or sample indices")
    rows = rows.reshape(-1, 4, 3)
    azimuth = np.deg2rad(rows[:, :, 1])
    elevation = np.deg2rad(90 - rows[:, :, 2])
    time_s = np.arange(len(rows)) / 50000
    # Spectral discovery gave ~182.416664 and ~9.999998 Hz. These simple
    # rational hypotheses retain the held-out accuracy and bound long-run phase.
    spin_hz, sweep_hz = 2189 / 12, 10
    terms = [(j, k) for j in range(2) for k in range(-7, 8) if j > 0 or k > 0]
    frequencies = np.array([j * spin_hz + k * sweep_hz for j, k in terms])

    def design(times):
        phase = 2 * np.pi * times[:, None] * frequencies[None, :]
        return np.column_stack([np.ones(len(times)), np.cos(phase), np.sin(phase)])

    targets = np.column_stack(
        [np.unwrap(azimuth, axis=0) + 2 * np.pi * spin_hz * time_s[:, None], elevation]
    )
    train = np.arange(0, 100000, 37)
    coefficients = np.linalg.lstsq(design(time_s[train]), targets[train], rcond=None)[0]
    report = {
        "source_revision": SOURCE_REVISION,
        "source_sha256": SOURCE_SHA256,
        "spin_hz": spin_hz,
        "sweep_hz": sweep_hz,
        "inferred_model_period_s": 12,
        "training_samples": len(train) * 4,
        "training_interval_s": [0, 2],
        "held_out_interval_s": [2, 4],
        "terms": terms,
        "coefficients_rad": coefficients.tolist(),
    }
    for name, lo, hi in [
        ("training_interval", 0, 100000),
        ("held_out", 100000, 200000),
    ]:
        angles = np.einsum("ij,jk->ik", design(time_s[lo:hi]), coefficients)
        a = angles[:, :4] - 2 * np.pi * spin_hz * time_s[lo:hi, None]
        e = angles[:, 4:]
        predicted = np.stack(
            [np.cos(e) * np.cos(a), np.cos(e) * np.sin(a), np.sin(e)], -1
        )
        a, e = azimuth[lo:hi], elevation[lo:hi]
        actual = np.stack([np.cos(e) * np.cos(a), np.cos(e) * np.sin(a), np.sin(e)], -1)
        error = np.rad2deg(
            np.arctan2(
                np.linalg.norm(np.cross(predicted, actual), axis=-1),
                np.sum(predicted * actual, axis=-1),
            )
        )
        report[name] = {
            "rms_deg_per_lane": np.sqrt(np.mean(error**2, axis=0)).tolist(),
            "p99_deg_per_lane": np.percentile(error, 99, axis=0).tolist(),
            "max_deg_per_lane": error.max(axis=0).tolist(),
        }
        if error.max() > 0.2:
            raise ValueError(
                "angular error exceeds the 0.2 degree model acceptance bound"
            )
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Derived measurement data from Livox-SDK/livox_laser_simulation.",
        "// Upstream Copyright (c) 2021 livox. See NOTICE.md for MIT terms.",
        "// Generated by scripts/fit-mid360-pattern.py; do not edit by hand.",
        f"// Source revision: {SOURCE_REVISION}",
        f"// Source SHA-256: {SOURCE_SHA256}",
        "pub(super) const TERMS: [(i32, i32); 22] = [",
    ]
    lines += [f"    ({j}, {k})," for j, k in terms]
    lines += ["];", "pub(super) const COEFFICIENTS_RAD: [[f64; 8]; 45] = ["]
    for row in coefficients:
        lines += (
            ["    ["] + [f"        {float(value)!r}," for value in row] + ["    ],"]
        )
    lines += ["];", ""]
    args.rust_output.write_text("\n".join(lines))
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(
        json.dumps(
            {k: v for k, v in report.items() if k != "coefficients_rad"}, indent=2
        )
    )


if __name__ == "__main__":
    main()
