"""Quantize a hardware optical fit to quarter-degree integers and prune zeros.

Reports differences from the fitted model over a declared uniform phase grid,
not physical angular noise or additional independent hardware validation.
"""

import argparse
import json
from pathlib import Path

import numpy as np

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("model", type=Path)
parser.add_argument("--rust-output", type=Path, required=True)
parser.add_argument("--report", type=Path, required=True)
parser.add_argument(
    "--profile-output",
    type=Path,
    help="Optional simplified profile for the transfer checker",
)
args = parser.parse_args()
p = json.loads(args.model.read_text())
c = np.array(p["coefficients"])
terms = np.array(p["terms"])
n = len(terms)
quantized = np.rint(np.rad2deg(c) * 4).astype(np.int64)
active = np.flatnonzero(
    np.any((quantized[:, 1 : 1 + n] != 0) | (quantized[:, 1 + n :] != 0), axis=(0, 2))
)
selected = np.r_[0, 1 + active, 1 + n + active]
packed = quantized[:, selected]
if not np.all(abs(packed) <= 32767):
    raise ValueError("quarter-degree coefficients do not fit i16")
phase = np.linspace(0, 2 * np.pi, 180, endpoint=False)
spin, sweep = np.meshgrid(phase, phase)
spin, sweep = spin.ravel(), sweep.ravel()
phases = spin[:, None] * terms[:, 0] + sweep[:, None] * terms[:, 1]
mat = np.column_stack([np.ones(len(spin)), np.cos(phases), np.sin(phases)])
errors = []
for lane in range(4):
    rays = []
    for co in [c[lane], np.deg2rad(quantized[lane] / 4)]:
        angles = np.einsum("ij,jk->ik", mat, co)
        angles[:, 0] += spin
        az, el = angles.T
        rays.append(
            np.column_stack(
                [np.cos(el) * np.cos(az), np.cos(el) * np.sin(az), np.sin(el)]
            )
        )
    a, b = rays
    errors.extend(
        np.rad2deg(
            np.arctan2(np.linalg.norm(np.cross(a, b), axis=1), np.sum(a * b, axis=1))
        )
    )
e = np.array(errors)
report = dict(
    source_capture_sha256=p["source_capture_sha256"],
    coefficient_step_deg=0.25,
    original_terms=n,
    retained_terms=len(active),
    grid="180x180 uniform spin/sweep phases per lane; 129600 directions",
    rms_difference_deg=float(np.sqrt(np.mean(e * e))),
    p95_difference_deg=float(np.percentile(e, 95)),
    maximum_difference_deg=float(e.max()),
    coefficient_and_term_bytes=int(packed.size * 2 + len(active) * 2),
    caveat="difference from the fitted optics, not calibrated physical noise",
)
lines = [
    "// SPDX-License-Identifier: MIT OR Apache-2.0",
    "// Quantized fitted parameters; original measurements retain their ownership.",
    "// Generated by scripts/simplify-hardware-optics.py; do not edit by hand.",
    "// Source capture SHA-256: " + p["source_capture_sha256"],
    f"pub(super) const NOMINAL_TERMS: [(i8, i8); {len(active)}] = [",
]
lines += [f"    ({j}, {k})," for j, k in terms[active]]
lines += [
    "];",
    f"pub(super) const QUARTER_DEGREE_COEFFICIENTS: [[[i16; 2]; {len(selected)}]; 4] = [",
]
for lane in packed:
    lines += ["    ["] + [f"        [{a}, {b}]," for a, b in lane] + ["    ],"]
lines += ["];", ""]
args.rust_output.write_text("\n".join(lines))
args.report.write_text(json.dumps(report, indent=2) + "\n")
print(json.dumps(report, indent=2))

if args.profile_output:
    obj = dict(
        source_capture_sha256=p["source_capture_sha256"],
        terms=p["terms"],
        coefficients=np.deg2rad(quantized / 4).tolist(),
    )
    args.profile_output.write_text(json.dumps(obj, indent=2) + "\n")
